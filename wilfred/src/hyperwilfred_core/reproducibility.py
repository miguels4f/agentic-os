"""Reproducibility of generated artifacts — regenerate in a fresh worktree, compare bytes.

The objective declares each generated artifact with its documented regeneration ``command`` and
any ``volatile_fields`` (JSON keys that may legitimately differ, e.g. ``generated_at``). The
verify step creates a throw-away git worktree of the committed ref, records the committed bytes,
runs the command there, and fails when the regenerated file differs — except in declared volatile
fields. A missing artifact, a failing/timed-out command or an uncommitted artifact all FAIL
(fail closed). The command is one argv-style command (``shlex`` split, no shell); wrap pipelines
in a script. Nothing here touches the network on its own.
"""

from __future__ import annotations

import json
import os
import shlex
import shutil
import subprocess
import tempfile
from pathlib import Path

from pydantic import BaseModel, Field

from hyperwilfred_core.schemas import GeneratedArtifact

DEFAULT_TIMEOUT_S = 300


class ArtifactResult(BaseModel):
    path: str
    ok: bool
    detail: str = ""


class ReproducibilityReport(BaseModel):
    ok: bool = True
    ref: str = "HEAD"
    results: list[ArtifactResult] = Field(default_factory=list)
    message: str = ""


def _strip_volatile(node: object, patterns: list[list[str]], trail: tuple[str, ...] = ()) -> object:
    """Drop dict keys whose dotted path matches a volatile pattern (``*`` matches any segment)."""
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            here = (*trail, str(k))
            if any(len(p) == len(here) and all(a in ("*", b) for a, b in zip(p, here, strict=True))
                   for p in patterns):
                continue
            out[k] = _strip_volatile(v, patterns, here)
        return out
    if isinstance(node, list):
        return [_strip_volatile(v, patterns, (*trail, str(i))) for i, v in enumerate(node)]
    return node


def compare_bytes(committed: bytes, regenerated: bytes, volatile_fields: list[str]) -> str | None:
    """None if equal (modulo declared volatile JSON fields), else a short reason."""
    if committed == regenerated:
        return None
    if volatile_fields:
        try:
            a = json.loads(committed)
            b = json.loads(regenerated)
        except ValueError:
            return "bytes differ and the file is not JSON, so volatile fields cannot apply"
        patterns = [f.split(".") for f in volatile_fields]
        if _strip_volatile(a, patterns) == _strip_volatile(b, patterns):
            return None
        return f"content differs outside the declared volatile fields {volatile_fields}"
    return "regenerated bytes differ from the committed bytes"


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=False
    )


def check(
    *,
    repo_root: Path,
    artifacts: list[GeneratedArtifact],
    ref: str = "HEAD",
    timeout_s: int = DEFAULT_TIMEOUT_S,
) -> ReproducibilityReport:
    """Regenerate every declared artifact in a fresh worktree of *ref* and compare."""
    if not artifacts:
        return ReproducibilityReport(ok=True, ref=ref, message="no generated artifacts declared")
    tmp_parent = Path(tempfile.mkdtemp(prefix="hw-repro-"))
    work = tmp_parent / "wt"
    results: list[ArtifactResult] = []
    added = _git(repo_root, "worktree", "add", "--detach", str(work), ref)
    try:
        if added.returncode != 0:
            return ReproducibilityReport(
                ok=False, ref=ref,
                message=f"could not create a fresh worktree of {ref!r}: {added.stderr.strip()}",
            )
        for art in artifacts:
            results.append(_check_one(work, art, timeout_s))
    finally:
        _git(repo_root, "worktree", "remove", "--force", str(work))
        shutil.rmtree(tmp_parent, ignore_errors=True)
    bad = [r for r in results if not r.ok]
    return ReproducibilityReport(
        ok=not bad, ref=ref, results=results,
        message="; ".join(f"{r.path}: {r.detail}" for r in bad),
    )


def _scrubbed_env(work: Path) -> dict[str, str]:
    """The command comes from agent-written plan data: never hand it the operator's secrets.

    Only PATH/locale survive; HOME points at the throw-away worktree so credential files under
    the real home (~/.aws, ~/.config/gh, …) are not where the command looks for them.
    """
    keep = {k: v for k, v in os.environ.items() if k in {"PATH", "LANG", "LC_ALL", "TZ"}}
    return {**keep, "HOME": str(work)}


def _check_one(work: Path, art: GeneratedArtifact, timeout_s: int) -> ArtifactResult:
    try:
        targets = sorted(p for p in work.glob(art.path) if p.is_file())
    except (NotImplementedError, ValueError, OSError) as exc:
        return ArtifactResult(path=art.path, ok=False, detail=f"unusable artifact path: {exc}")
    if not targets:
        return ArtifactResult(
            path=art.path, ok=False,
            detail="not present in the committed tree — commit the generated artifact first",
        )
    before = {t: t.read_bytes() for t in targets}
    # The command must PRODUCE the bytes: remove every target first (this is a throw-away
    # worktree), so a do-nothing command (`true`, `git status`) can never pass as "reproducible".
    for t in targets:
        t.unlink()
    try:
        proc = subprocess.run(
            shlex.split(art.command), cwd=work, capture_output=True, text=True,
            timeout=timeout_s, check=False, env=_scrubbed_env(work),
        )
    except (OSError, ValueError, subprocess.TimeoutExpired) as exc:
        return ArtifactResult(path=art.path, ok=False, detail=f"regeneration command failed: {exc}")
    if proc.returncode != 0:
        return ArtifactResult(
            path=art.path, ok=False,
            detail=f"regeneration command exited {proc.returncode}: {proc.stderr.strip()[-300:]}",
        )
    for t, old in before.items():
        if not t.exists():
            return ArtifactResult(
                path=art.path, ok=False,
                detail=f"{t.relative_to(work)} was not recreated by the regeneration command",
            )
        reason = compare_bytes(old, t.read_bytes(), art.volatile_fields)
        if reason:
            rel = t.relative_to(work)
            return ArtifactResult(path=art.path, ok=False, detail=f"{rel}: {reason}")
    after = sorted(p for p in work.glob(art.path) if p.is_file())
    extra = [str(p.relative_to(work)) for p in after if p not in before]
    if extra:
        return ArtifactResult(
            path=art.path, ok=False,
            detail=f"regeneration produced files that are not committed: {extra[:5]}",
        )
    return ArtifactResult(path=art.path, ok=True, detail="reproducible")


__all__ = ["ReproducibilityReport", "check", "compare_bytes"]
